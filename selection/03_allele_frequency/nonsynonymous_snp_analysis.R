##### filter genes for visualization #####

# Keep genes with alternate allele frequency >= 0.20
# in at least one genetic cluster.
genes_keep <- plot_df %>%
  filter(!is.na(gene_label)) %>%
  group_by(gene_label) %>%
  summarise(
    max_alt_freq = max(
      alt_freq,
      na.rm = TRUE
    ),
    .groups = "drop"
  ) %>%
  filter(
    max_alt_freq >= 0.20
  ) %>%
  pull(gene_label)


plot_df_filtered <- plot_df %>%
  filter(
    gene_label %in% genes_keep
  )

# preserve gene order after filtering
plot_df_filtered$gene_label <- factor(
  plot_df_filtered$gene_label,
  levels = levels(plot_df$gene_label)
)


##### plot alternate allele frequencies #####

p_gene <- ggplot(
  plot_df_filtered,
  aes(
    x = gene_label,
    y = alt_freq,
    fill = cluster
  )
) +
  geom_col() +
  
  facet_wrap(
    ~ cluster,
    ncol = 1
  ) +
  
  scale_fill_manual(
    values = cluster_colors,
    name = "Genetic Cluster"
