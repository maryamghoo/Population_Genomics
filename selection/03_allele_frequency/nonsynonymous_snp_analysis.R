##### identify gene presence among genetic clusters #####

# A gene is considered present in a genetic cluster when the
# alternate allele frequency is greater than zero.
gene_presence <- plot_df %>%
  filter(
    alt_freq > 0,
    !is.na(gene_symbol)
  ) %>%
  distinct(
    gene_symbol,
    cluster
  )

# count genetic clusters containing each gene
gene_counts <- gene_presence %>%
  group_by(gene_symbol) %>%
  summarise(
    n_clusters = n_distinct(cluster),
    
    clusters = paste(
      sort(unique(cluster)),
      collapse = ", "
    ),
    
    .groups = "drop"
  )

# Genes present in one genetic cluster
genes_in_1_cluster <- gene_counts %>%
  filter(n_clusters == 1)

# Genes present in two genetic clusters
genes_in_2_clusters <- gene_counts %>%
  filter(n_clusters == 2)

# Genes present in three genetic clusters
genes_in_3_clusters <- gene_counts %>%
  filter(n_clusters == 3)

# Genes present in four genetic clusters
genes_in_4_clusters <- gene_counts %>%
