##### define directories #####

# directory containing Bash inputs that is also needed here
bash_data <- "bash_data"

# directory containing Bash outputs
bash_dir <- "bash_results"

# directory for R outputs
output_dir <- "r_results"

dir.create(output_dir, showWarnings = FALSE)

##### read ANNOVAR annotation #####
annotation <- read_tsv(
  file.path(
    bash_data,
    "fdr_outliers_annotated.fsj_multianno.txt"
  ),
  show_col_types = FALSE
)


##### identify nonsynonymous SNPs #####

nonsyn_annotation <- annotation %>%
  filter(ExonicFunc.refGene == "nonsynonymous SNV") %>%
  mutate(
    snp = paste(Chr, Start, sep = ":"),
    
    gene_id = str_split(
      AAChange.refGene,
      ":",
      simplify = TRUE
    )[, 1],
    
    aa_change = str_split(
      AAChange.refGene,
      ":",
      simplify = TRUE
    )[, 5],
    
    snp_label = paste(
      gene_id,
      aa_change
    )
  ) %>%
  select(
    snp,
    gene_id,
    aa_change,
    snp_label
  )


##### create candidate-gene summary #####

# Summarize nonsynonymous SNPs and start-loss variants by gene
candidate_genes <- annotation %>%
  filter(Func.refGene == "exonic") %>%
  mutate(
    Gene_symbol = str_split(
      AAChange.refGene,
      ":",
      simplify = TRUE
    )[, 2]
  ) %>%
  group_by(
    Gene.refGene,
    Gene_symbol
  ) %>%
  summarise(
    n_nonsyn = sum(
      ExonicFunc.refGene == "nonsynonymous SNV"
    ),
    
    n_startloss = sum(
      ExonicFunc.refGene == "startloss"
    ),
    
    positions = paste(
      paste0(Chr, ":", Start),
      collapse = "; "
    ),
    
    aa_changes = paste(
      AAChange.refGene,
      collapse = "; "
    ),
    
    .groups = "drop"
  ) %>%
  filter(
    n_nonsyn > 0 |
      n_startloss > 0
  ) %>%
  arrange(desc(n_nonsyn))

write.csv(
  candidate_genes,
  file.path(
    output_dir,
    "candidate_genes_table.csv"
  ),
  row.names = FALSE
)


##### read cluster allele frequencies #####

# Generated by nonsynonymous_snp_frequencies.sh
frequency_data <- read_tsv(
  file.path(
    bash_dir,
    "all_pop_freq.txt"
  ),
  show_col_types = FALSE
)

# separate allele and frequency information 
frequency_data <- frequency_data %>%
  mutate(
    ref_allele = str_split(
      ALLELE1,
      ":",
      simplify = TRUE
    )[, 1],
    
    ref_freq = as.numeric(
      str_split(
        ALLELE1,
        ":",
        simplify = TRUE
      )[, 2]
    ),
    
    alt_allele = str_split(
      ALLELE2,
      ":",
      simplify = TRUE
    )[, 1],
    
    alt_freq = as.numeric(
      str_split(
        ALLELE2,
        ":",
        simplify = TRUE
      )[, 2]
    ),
    
    snp = paste(
      CHROM,
      POS,
      sep = ":"
    )
  )

# combine allele frequencies with SNP annotation
plot_df <- frequency_data %>%
  left_join(
    nonsyn_annotation,
    by = "snp"
  )


